    const codes = ['tr', 'en', 'de', 'fr', 'es', 'ru', 'zh', 'ar'];
    final values = _v50[key];
    if (values == null) return key;
    final index = codes.indexOf(langCode);
    return values[index < 0 ? 1 : index];
  }

